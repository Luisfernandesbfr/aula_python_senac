# Exercício 8: Verificação de Múltiplo de 5
# Escreva um programa que peça um número inteiro. Se o número for múltiplo de 5, imprima "O número é múltiplo de 5."

numero = int(input("Digite um numero:"))

if numero % 5 == 0:
    print(" O numero é multiplo de 5 ")
else :
    print(" O numero não é multiplo de 5 ")    
